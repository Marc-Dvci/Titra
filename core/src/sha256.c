static uint32_t rotr(uint32_t x, unsigned n) { return (x >> n) | (x << (32u - n)); }

static void compress(uint32_t h[8], const unsigned char *p) {
    uint32_t w[64];
    for (int i = 0; i < 16; i++) {
        w[i] = ((uint32_t)p[i * 4] << 24) | ((uint32_t)p[i * 4 + 1] << 16) | ((uint32_t)p[i * 4 + 2] << 8) | (uint32_t)p[i * 4 + 3];
    }
    for (int i = 16; i < 64; i++) {
        const uint32_t s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >> 3);
        const uint32_t s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }
    uint32_t a = h[0], b = h[1], c = h[2], d = h[3], e = h[4], f = h[5], g = h[6], k = h[7];
    for (int i = 0; i < 64; i++) {
        const uint32_t s1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
        const uint32_t ch = (e & f) ^ (~e & g);
        const uint32_t t1 = k + s1 + ch + K[i] + w[i];
        const uint32_t s0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
        const uint32_t maj = (a & b) ^ (a & c) ^ (b & c);
        const uint32_t t2 = s0 + maj;
        k = g;
        g = f;
        f = e;
        e = d + t1;
        d = c;
        c = b;
        b = a;
        a = t1 + t2;
    }
    h[0] += a;
    h[1] += b;
    h[2] += c;
    h[3] += d;
    h[4] += e;
    h[5] += f;
    h[6] += g;
    h[7] += k;
}

void titra_sha256_init(titra_sha256_t *s) {
    static const uint32_t IV[8] = {0x6a09e667u, 0xbb67ae85u, 0x3c6ef372u, 0xa54ff53au, 0x510e527fu, 0x9b05688cu, 0x1f83d9abu, 0x5be0cd19u};
    memcpy(s->h, IV, sizeof IV);
    s->total = 0;
    s->fill = 0;
}

void titra_sha256_update(titra_sha256_t *s, const void *data, size_t n) {
    const unsigned char *p = data;
    s->total += n;
    if (s->fill > 0) {
        const size_t take = n < 64 - s->fill ? n : 64 - s->fill;
        memcpy(s->block + s->fill, p, take);
        s->fill += take;
        p += take;
        n -= take;
        if (s->fill == 64) {
            compress(s->h, s->block);
            s->fill = 0;
        }
    }
    while (n >= 64) {
        compress(s->h, p);
        p += 64;
        n -= 64;
    }
    if (n > 0) {
        memcpy(s->block, p, n);
        s->fill = n;
    }
}

void titra_sha256_final_hex(titra_sha256_t *s, char hex[65]) {
    const uint64_t bits = s->total * 8u;
    unsigned char pad = 0x80;
    titra_sha256_update(s, &pad, 1);
    pad = 0;
    while (s->fill != 56) titra_sha256_update(s, &pad, 1);
    unsigned char len[8];
    for (int i = 0; i < 8; i++) len[i] = (unsigned char)(bits >> (56 - 8 * i));
    titra_sha256_update(s, len, 8);
    for (int i = 0; i < 8; i++) snprintf(hex + i * 8, 9, "%08x", s->h[i]);
    hex[64] = '\0';
}
