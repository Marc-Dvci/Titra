"""Trains the early-warning model on the development seeds and writes it as C (core/src/risk_model.inc).

    pip install scikit-learn==1.5.2
    python scripts/train_risk.py [--cv-only]

Everything here uses the development seeds, split by seed for the choice of size. The held-out seeds are not read.
Run from the repository root, after `make -C core build/libtitra_core.so`.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402
from sklearn.ensemble import GradientBoostingClassifier  # noqa: E402
from sklearn.metrics import roc_auc_score  # noqa: E402

from bench import risk  # noqa: E402

GRID = [(30, 2), (60, 2), (30, 3), (60, 3), (100, 3)]
FINAL = (60, 2)
LEARNING_RATE = 0.08
SUBSAMPLE = 0.8


def fit(x: np.ndarray, y: np.ndarray, trees: int, depth: int) -> GradientBoostingClassifier:
    return GradientBoostingClassifier(
        n_estimators=trees, max_depth=depth, learning_rate=LEARNING_RATE, subsample=SUBSAMPLE, random_state=0
    ).fit(x, y)


def cross_validate(rows: list[risk.Row]) -> list[dict[str, float]]:
    """Leave-one-seed-out AUROC for each model size, development seeds only."""
    x = np.array([r.x for r in rows])
    y = np.array([r.y for r in rows])
    seeds = np.array([r.seed for r in rows])
    results = []
    for trees, depth in GRID:
        preds = np.zeros(len(rows))
        for s in sorted(set(seeds.tolist())):
            test = seeds == s
            preds[test] = fit(x[~test], y[~test], trees, depth).predict_proba(x[test])[:, 1]
        results.append({"trees": trees, "depth": depth, "auroc": round(float(roc_auc_score(y, preds)), 4)})
        print(results[-1], flush=True)
    return results


def write_c(model: GradientBoostingClassifier, path: Path) -> int:
    """Flat arrays: one root per tree, children by index, and a leaf's feature is -1."""
    feature: list[int] = []
    threshold: list[float] = []
    left: list[int] = []
    right: list[int] = []
    value: list[float] = []
    roots: list[int] = []
    depth_max = 0
    for est in model.estimators_[:, 0]:
        t = est.tree_
        base = len(feature)
        roots.append(base)
        depth_max = max(depth_max, int(t.max_depth))
        for i in range(t.node_count):
            leaf = t.children_left[i] == -1
            feature.append(-1 if leaf else int(t.feature[i]))
            threshold.append(0.0 if leaf else float(t.threshold[i]))
            left.append(-1 if leaf else base + int(t.children_left[i]))
            right.append(-1 if leaf else base + int(t.children_right[i]))
            value.append(float(t.value[i][0][0]) * LEARNING_RATE if leaf else 0.0)
    # The ensemble starts from the log-odds of the base rate.
    prior = float(model.init_.class_prior_[1])
    base_value = float(np.log(prior / (1.0 - prior)))

    def ints(a: list[int]) -> str:
        return ",".join(str(v) for v in a)

    def floats(a: list[float]) -> str:
        return ",".join(f"{v:.9g}" for v in a)

    text = (
        "/* Generated by scripts/train_risk.py from the development seeds. Do not edit. */\n"
        f"#define RISK_TREES {len(roots)}\n#define RISK_DEPTH {depth_max}\n#define RISK_NODES {len(feature)}\n"
        f"static const double RISK_BASE = {base_value:.9g};\n"
        f"static const int RISK_ROOT[RISK_TREES] = {{{ints(roots)}}};\n"
        f"static const short RISK_FEATURE[RISK_NODES] = {{{ints(feature)}}};\n"
        f"static const double RISK_THRESHOLD[RISK_NODES] = {{{floats(threshold)}}};\n"
        f"static const short RISK_LEFT[RISK_NODES] = {{{ints(left)}}};\n"
        f"static const short RISK_RIGHT[RISK_NODES] = {{{ints(right)}}};\n"
        f"static const double RISK_VALUE[RISK_NODES] = {{{floats(value)}}};\n"
    )
    path.write_text(text, encoding="utf-8")
    return len(feature)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cv-only", action="store_true")
    a = ap.parse_args()
    rows = risk.build("development")
    print(f"{len(rows)} minutes, {sum(r.y for r in rows)} with a dip ahead", flush=True)
    grid = cross_validate(rows)
    (ROOT / "eval" / "risk_training_log.json").write_text(
        json.dumps({"final": {"trees": FINAL[0], "depth": FINAL[1]}, "grid_leave_one_seed_out": grid}, indent=1) + "\n",
        encoding="utf-8",
    )
    if a.cv_only:
        return
    x = np.array([r.x for r in rows])
    y = np.array([r.y for r in rows])
    model = fit(x, y, *FINAL)
    nodes = write_c(model, ROOT / "core" / "src" / "risk_model.inc")
    for name, imp in sorted(zip(risk.NAMES, model.feature_importances_, strict=True), key=lambda p: -p[1])[:6]:
        print(f"  {name:20s} {imp:.3f}")
    print(f"wrote {FINAL[0]} trees, {nodes} nodes")


if __name__ == "__main__":
    main()
